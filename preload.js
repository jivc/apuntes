const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('apuntes', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (patch) => ipcRenderer.invoke('config:set', patch),
  detectDropbox: () => ipcRenderer.invoke('vault:detect-dropbox'),
  chooseVault: () => ipcRenderer.invoke('vault:choose'),
  useVault: (dir) => ipcRenderer.invoke('vault:use', dir),
  loadNotes: () => ipcRenderer.invoke('notes:load'),
  loadTrash: () => ipcRenderer.invoke('notes:trash-list'),
  writeNote: (p, content) => ipcRenderer.invoke('notes:write', p, content),
  writeNoteSync: (p, content) => ipcRenderer.sendSync('notes:write-sync', p, content),
  createNote: (content) => ipcRenderer.invoke('notes:create', content),
  renameNote: (p, title) => ipcRenderer.invoke('notes:rename', p, title),
  trashNote: (p) => ipcRenderer.invoke('notes:trash', p),
  restoreNote: (p) => ipcRenderer.invoke('notes:restore', p),
  deleteForever: (p) => ipcRenderer.invoke('notes:delete-forever', p),
  removeEmpty: (p, untouched) => ipcRenderer.invoke('notes:remove-empty', p, untouched),
  getMeta: () => ipcRenderer.invoke('meta:get'),
  setMeta: (meta) => ipcRenderer.invoke('meta:set', meta),
  archiveNote: (p) => ipcRenderer.invoke('notes:archive', p),
  popupMenu: (items) => ipcRenderer.invoke('menu:popup', items),
  onMetaChanged: (cb) => ipcRenderer.on('meta:changed', (_e, meta) => cb(meta)),
  saveAttachment: (name, bytes) => ipcRenderer.invoke('attach:save', name, bytes),
  exportSave: (opts) => ipcRenderer.invoke('export:save', opts),
  exportPdf: (opts) => ipcRenderer.invoke('export:pdf', opts),
  print: (html) => ipcRenderer.invoke('export:print', html),
  writeClipboard: (data) => ipcRenderer.invoke('clipboard:write', data),
  reveal: (p) => ipcRenderer.invoke('shell:reveal', p),
  openFolder: () => ipcRenderer.invoke('shell:open-folder'),
  openExternal: (url) => ipcRenderer.invoke('shell:open', url),
  setTitlebar: (colors) => ipcRenderer.send('titlebar', colors),
  onNoteChanged: (cb) => ipcRenderer.on('note:changed', (_e, note) => cb(note)),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, action) => cb(action)),
  onNoteRemoved: (cb) => ipcRenderer.on('note:removed', (_e, p) => cb(p)),
});
